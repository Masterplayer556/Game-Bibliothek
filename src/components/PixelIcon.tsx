export type PixelIconName = keyof typeof ICONS;

/** One path per icon: a run of pixels in a row becomes one rectangle. */
function pathOf(rows: readonly string[]): string {
  let d = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== "#") continue;
      let end = x;
      while (row[end + 1] === "#") end++;
      d += `M${x} ${y}h${end - x + 1}v1h-${end - x + 1}z`;
      x = end;
    }
  });
  return d;
}

export function PixelIcon({ name, className = "h-4 w-4" }: { name: PixelIconName; className?: string }) {
  return (
    <svg viewBox="0 0 12 12" className={`shrink-0 ${className}`} fill="currentColor" shapeRendering="crispEdges" aria-hidden focusable="false">
      <path d={pathOf(ICONS[name])} />
    </svg>
  );
}
